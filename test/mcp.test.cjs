  const transport = new StdioClientTransport({
    command: process.execPath,
    args: [path.join(__dirname, '..', 'server.cjs')],
    env: { ...process.env, CODEX_LINK_DATA_DIR: directory, CODEX_LINK_VAULT: fs.realpathSync(directory) },
  });
  const client = new Client({ name: 'integration-test', version: '1.0.0' });
  t.after(async () => {
    await client.close();
    fs.rmSync(directory, { recursive: true, force: true });
  });
  await client.connect(transport);
  const tools = await client.listTools();
  const names = tools.tools.map((item) => item.name);
  assert.ok(names.includes('open_integration_status'));
  assert.ok(names.includes('choerodon_todos'));
  assert.ok(names.includes('local_save_draft'));
  assert.ok(names.includes('draft_list'));
  assert.ok(names.includes('draft_read'));
  assert.ok(names.includes('knowledge_create'));
  assert.ok(names.includes('knowledge_catalog'));
  assert.ok(names.includes('knowledge_catalog_reservations'));
  assert.ok(names.includes('draft_publish'));
  assert.ok(names.includes('draft_publication_get'));
  assert.ok(names.includes('draft_preview_note_update'));
  assert.ok(names.includes('knowledge_recommend_locations'));
  assert.ok(names.includes('draft_note_update_cleanups'));
  assert.ok(names.includes('draft_note_update_cleanup'));
  assert.ok(names.includes('pending_note_links'));
  assert.ok(names.includes('pending_note_link'));
  assert.ok(names.includes('draft_publication_reservations'));
  assert.ok(names.includes('draft_publication_reservation_uncertain'));
  assert.ok(names.includes('draft_publication_reservation_status'));
  assert.equal((await client.callTool({ name: 'pending_note_link', arguments: { id: 'a'.repeat(64), userId: '1', confirmed: false } })).isError, true);
  const denied = await client.callTool({ name: 'knowledge_create', arguments: { path: 'note.md', content: '# 测试', confirmed: false } });
  assert.equal(denied.isError, true);
  const operationId = 'a'.repeat(64);
  const note = await client.callTool({ name: 'knowledge_create', arguments: { path: 'note.md', content: '# 测试', operationId, confirmed: true } });
  assert.ok(!note.isError);
  assert.equal(JSON.parse(note.content[0].text).status, 'completed');
  assert.equal((await client.callTool({ name: 'knowledge_create', arguments: { path: 'note.md', content: '# 测试', operationId, confirmed: true } })).isError, true);
  const catalog = JSON.parse((await client.callTool({ name: 'knowledge_catalog', arguments: {} })).content[0].text);
  assert.ok(catalog.items.some((item) => item.path === 'note.md' && item.origins.includes('created')));
  const duplicate = await client.callTool({ name: 'knowledge_create', arguments: { path: 'note.md', content: '覆盖', operationId: 'b'.repeat(64), confirmed: true } });
  assert.equal(duplicate.isError, true);
  const readNote = await client.callTool({ name: 'knowledge_read', arguments: { path: 'note.md' } });
  assert.equal(JSON.parse(readNote.content[0].text).content, '# 测试');
  const recommendations = await client.callTool({ name: 'knowledge_recommend_locations', arguments: { keywords: ['note'] } });
  assert.ok(JSON.parse(recommendations.content[0].text).candidates.some((item) => item.path === 'note.md'));
  assert.deepEqual(JSON.parse((await client.callTool({ name: 'draft_note_update_cleanups', arguments: {} })).content[0].text), []);
  assert.equal((await client.callTool({ name: 'draft_note_update_cleanup', arguments: { lockId: 'a'.repeat(32), confirmed: false } })).isError, true);
  const comparisonDraft = JSON.parse((await client.callTool({ name: 'local_save_draft', arguments: { title: '对比', target: 'note.md', content: '# 修改', confirmed: true } })).content[0].text);
  const comparisonArgs = { id: comparisonDraft.id, revision: comparisonDraft.revision, target: comparisonDraft.target, expectedContent: comparisonDraft.content };
  const historySource = JSON.parse((await client.callTool({ name: 'draft_history_source', arguments: comparisonArgs })).content[0].text);
  const historyArgs = { ...comparisonArgs, vaultId: historySource.vaultId, beforeDigest: historySource.revision, selection: { start: 0, end: historySource.content.length, text: historySource.content }, conclusion: '新的结论' };
  assert.notEqual((await client.callTool({ name: 'draft_history_candidate', arguments: historyArgs })).isError, true);
  assert.equal((await client.callTool({ name: 'draft_history_candidate', arguments: { ...historyArgs, beforeDigest: '0'.repeat(64) } })).isError, true);
  assert.equal(fs.readFileSync(path.join(directory, 'note.md'), 'utf8'), '# 测试');
  const comparison = JSON.parse((await client.callTool({ name: 'draft_preview_note_update', arguments: comparisonArgs })).content[0].text);
  assert.equal(comparison.removed, '# 测试');
  assert.equal(comparison.added, '# 修改');
  assert.equal((await client.callTool({ name: 'draft_preview_note_update', arguments: { ...comparisonArgs, expectedContent: '过期内容' } })).isError, true);
  const safeUpdatePreview = await client.callTool({ name: 'draft_note_update_preview', arguments: { ...comparisonArgs, requestId: 'mcp-update-test' } });
  assert.equal(safeUpdatePreview.isError, undefined);
  const safeUpdate = JSON.parse(safeUpdatePreview.content[0].text);
  assert.equal(safeUpdate.beforeContent, '# 测试');
  assert.equal(safeUpdate.afterContent, '# 修改');
  const { vaultId: expectedVaultId, beforeDigest, selection } = historyArgs;
  const appendArgs = { ...comparisonArgs, mode: 'append', vaultId: expectedVaultId, beforeDigest, selection };
  assert.equal((await client.callTool({ name: 'draft_note_update_preview', arguments: { ...appendArgs, vaultId: '0'.repeat(64) } })).isError, true);
  const appendResponse = await client.callTool({ name: 'draft_note_update_preview', arguments: appendArgs });
  assert.equal(appendResponse.isError, undefined);
  const appendPreview = JSON.parse(appendResponse.content[0].text);
  assert.equal(appendPreview.mode, 'append');
  assert.equal(appendPreview.conclusionFormat, 'markdown-source');
  assert.ok(appendPreview.afterContent.startsWith('# 测试\n'));
  assert.equal(appendPreview.removed, '');
  const unavailableUpdate = await client.callTool({ name: 'draft_note_update_submit', arguments: { ...comparisonArgs, requestId: safeUpdate.requestId, confirmation: safeUpdate.confirmation, confirmed: true } });
  assert.equal(unavailableUpdate.isError, undefined);
  assert.equal(JSON.parse(unavailableUpdate.content[0].text).status, 'not_written');
  assert.equal(fs.readFileSync(path.join(directory, 'note.md'), 'utf8'), '# 测试');
  await client.callTool({ name: 'local_delete_draft', arguments: { id: comparisonDraft.id, expectedRevision: comparisonDraft.revision, confirmed: true } });
  assert.ok(!names.some((name) => /yuque.*(write|update|create)/.test(name)));
  const invalid = await client.callTool({ name: 'local_save_draft', arguments: { title: '标题', content: '内容', confirmed: false } });
  assert.equal(invalid.isError, true);
