const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const crypto = require('node:crypto');
const { Client } = require('@modelcontextprotocol/sdk/client/index.js');
const { StdioClientTransport } = require('@modelcontextprotocol/sdk/client/stdio.js');
const { LocalStore } = require('../src/core.cjs');

test('MCP 多工作项草稿整体替换关联，发布及更新仅关联明确选择且当前身份可用的工作项', async (t) => {
  const directory = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), 'multi-issue-mcp-')));
  const vault = path.join(directory, 'vault'); fs.mkdirSync(vault);
  const dataDirectory = path.join(directory, 'index');
  const command = path.join(directory, 'c7n');
  fs.writeFileSync(command, `#!${process.execPath}\nif (process.argv[2] === 'info') console.log('用户 ID  123\\n登录名    test\\n租户     示例 (7)'); else process.exitCode = 1;\n`, { mode: 0o700 });
  const issue = { environment: 'https://example.test', tenantId: '7', projectId: '10', issueId: '1', title: '第一项', url: '' };
  const second = { ...issue, issueId: '2', title: '第二项' };
  const foreign = { ...issue, tenantId: '8', issueId: '3', title: '其他租户' };
  const hash = (value) => crypto.createHash('sha256').update(value).digest('hex');
  const store = new LocalStore(dataDirectory);
  const update = store.saveDraft({ title: '已更新', target: 'updated.md', content: '更新正文', issues: [issue, second, foreign] });
  fs.writeFileSync(path.join(vault, 'updated.md'), update.content);
  store.beginDraftUpdate({ id: update.id, revision: update.revision, target: update.target, content: update.content, updateLock: { requestId: 'multi-update', ownerPid: process.pid, vaultId: hash(vault), target: update.target, beforeDigest: hash('原文'), afterDigest: hash(update.content), status: 'preparing' } });
  store.finishDraftUpdate({ id: update.id, revision: update.revision, requestId: 'multi-update', outcome: 'completed' });
  const client = new Client({ name: 'multi-issue-test', version: '1' });
  t.after(async () => { await client.close(); fs.rmSync(directory, { recursive: true, force: true }); });
  await client.connect(new StdioClientTransport({ command: process.execPath, args: [path.join(__dirname, '..', 'server.cjs')], env: { ...process.env, CODEX_LINK_DATA_DIR: dataDirectory, CODEX_LINK_VAULT: vault, CODEX_LINK_C7N: command, C7N_API_URL: issue.environment } }));
  const call = (name, args) => client.callTool({ name, arguments: args });
  const read = async (name, args) => {
    const result = await call(name, args); assert.notEqual(result.isError, true, JSON.stringify(result)); return JSON.parse(result.content[0].text);
  };
  const draft = await read('local_save_draft', { title: '多项发布', target: 'created.md', content: '发布正文', issues: [issue, second, foreign], confirmed: true });
  assert.deepEqual(draft.issues, [issue, second, foreign]);
  assert.deepEqual(draft.issue, issue);
  const listed = await read('draft_list', {});
  assert.deepEqual(listed.items.find((entry) => entry.id === draft.id).issues, draft.issues);
  const input = { id: draft.id, revision: draft.revision, target: draft.target, expectedContent: draft.content };
  assert.equal((await read('draft_publish', { ...input, confirmed: true })).status, 'completed');
  assert.equal((await call('draft_link_publication', { ...input, userId: '123', confirmed: true })).isError, true);
  assert.equal((await call('draft_link_publication', { ...input, issue: { ...issue, issueId: 'missing' }, userId: '123', confirmed: true })).isError, true);
  await read('draft_link_publication', { ...input, issue: second, userId: '123', confirmed: true });
  assert.equal((await call('draft_link_publication', { ...input, issue: foreign, userId: '123', confirmed: true })).isError, true);
  const updateInput = { id: update.id, revision: update.revision, requestId: 'multi-update', userId: '123', confirmed: true };
  assert.equal((await call('draft_note_update_link', updateInput)).isError, true);
  await read('draft_note_update_link', { ...updateInput, issue: second });
  assert.equal((await call('draft_note_update_link', { ...updateInput, issue: foreign })).isError, true);
  const state = await read('local_list', {});
  assert.deepEqual(state.noteLinks.map((entry) => [entry.path, entry.issue.issueId]).sort(), [['created.md', '2'], ['updated.md', '2']]);
  assert.equal(state.pendingNoteLinks.filter((entry) => entry.issue.issueId !== '2').length, 4);
  assert.equal(fs.readFileSync(path.join(vault, 'created.md'), 'utf8'), draft.content);
  const cleared = await read('local_save_draft', { id: draft.id, expectedRevision: draft.revision, title: draft.title, target: draft.target, content: draft.content, issues: [], confirmed: true });
  assert.deepEqual(cleared.issues, []);
  assert.equal(cleared.issue, undefined);
  assert.equal((await call('local_save_draft', { title: '超限', content: '正文', issues: Array.from({ length: 101 }, (_, index) => ({ ...issue, issueId: String(index) })), confirmed: true })).isError, true);
});
